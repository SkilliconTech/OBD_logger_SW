_MAP = " See the bank mapping note."


def _oxygen(first, name, what):
    """Eight oxygen sensor slots that follow the same pattern."""
    return [(f"{first + i:02X}", f"{name}, slot {i + 1}",
             f"Returns {what} for oxygen sensor slot {i + 1}.{_MAP}")
            for i in range(8)]


_RAW += _oxygen(0x14, "Conventional oxygen sensor",
                "sensor voltage and associated short-term fuel trim")
_RAW += _oxygen(0x24, "Wide-range oxygen sensor, voltage",
                "equivalence ratio and sensor voltage")
_RAW += _oxygen(0x34, "Wide-range oxygen sensor, current",
                "equivalence ratio and sensor current")

DATA_PIDS = tuple(sorted((Entry(*row) for row in _RAW),
                         key=lambda e: int(e.ident, 16)))